/** Выбор случайной фразы без повтора предыдущей. */
const lastShown = new Map<string, string>()

export function pick(key: string, list: string[]): string {
  if (list.length === 0) return ''
  if (list.length === 1) return list[0]!
  const previous = lastShown.get(key)
  const options = list.filter((item) => item !== previous)
  const chosen = options[Math.floor(Math.random() * options.length)]!
  lastShown.set(key, chosen)
  return chosen
}

export function greetingForNow(date = new Date()): string {
  const hour = date.getHours()
  if (hour >= 5 && hour < 12) return pick('greeting', greetings.morning)
  if (hour >= 12 && hour < 17) return pick('greeting', greetings.day)
  if (hour >= 17 && hour < 23) return pick('greeting', greetings.evening)
  return pick('greeting', greetings.night)
}
